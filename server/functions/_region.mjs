/** 설치 주소 → 요금 지역 (서울·경기·인천 = metro 월 30,000원 / 그 외 = other 월 40,000원, 1곳 · 부가세 별도)
 *  pay.html 에 같은 규칙의 복사본이 있다 — 바꾸면 함께 고칠 것.
 *  1) 「서울·경기·인천」으로 시작하면 수도권 (주소 검색 결과는 대부분 이 형태)
 *  2) 시·도 없이 적은 주소는 수도권에만 있는 시·군·구 이름으로 판정 (예: 「성남시 분당구 …」 「부평구 …」)
 *     — 「중구·동구·서구·남구·북구·강서구·광주」처럼 다른 시·도에도 있는 이름은 쓰지 않는다
 *  3) 그 밖에는 그 외 지역. 금액은 서버가 이 규칙으로 정하고, 화면은 같은 규칙으로 미리 보여 준다. */
const METRO_HEAD = /^(서울|경기|인천)/;
const METRO_PLACE = new RegExp("^(" + [
  // 서울 자치구 (다른 시·도와 겹치는 중구·강서구 제외)
  "강남구", "서초구", "송파구", "강동구", "마포구", "용산구", "성동구", "광진구", "동대문구", "중랑구", "성북구", "강북구", "도봉구", "노원구",
  "은평구", "서대문구", "종로구", "양천구", "구로구", "금천구", "영등포구", "동작구", "관악구",
  // 경기 시·군 (광주 제외 — 광주광역시와 겹침)
  "수원", "성남", "고양", "용인", "부천", "안산", "안양", "남양주", "화성", "평택", "의정부", "시흥", "파주", "광명", "김포", "군포", "이천",
  "양주", "오산", "구리", "안성", "포천", "의왕", "하남", "여주", "동두천", "과천", "가평", "양평", "연천",
  // 인천 구·군 (중구·동구·서구 제외)
  "미추홀구", "연수구", "남동구", "부평구", "계양구", "강화", "옹진",
].join("|") + ")");
export function regionOf(addr) {
  const a = String(addr || "").replace(/^\s*\(?\d{5}\)?\s*/, "").replace(/^대한민국\s*/, "").trim();
  if (!a) return null;
  return METRO_HEAD.test(a) || METRO_PLACE.test(a) ? "metro" : "other";
}
